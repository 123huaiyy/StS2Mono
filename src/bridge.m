// StS2Mono: runs the C# code of the Slay the Spire 2 iOS port on Mono instead
// of its NativeAOT build, so that the game's own mod loader can load DLL mods.
//
// How it hooks in: the port's engine is the official Godot 4.5.1 template. When
// it starts .NET it probes <api_assemblies_dir>/libhostfxr.so, then
// libcoreclr.so, then libmonosgen-2.0.so, and only falls back to the NativeAOT
// framework when none exists (modules/mono/mono_gd/gd_mono.cpp). On this port
// api_assemblies_dir is Library/Caches/data_sts2_ios_arm64. At load time this
// dylib links libmonosgen-2.0.so there to itself, so Godot calls the
// coreclr_initialize / coreclr_create_delegate below, which start Mono's
// interpreter on the IL assemblies in Documents/dotnet.

#import <Foundation/Foundation.h>
#include <dlfcn.h>
#include <fcntl.h>
#include <pthread.h>
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/time.h>
#include <unistd.h>

#include <mono/jit/jit.h>
#include <mono/metadata/mono-debug.h>
#include <mono/utils/mono-logger.h>

#ifndef BRIDGE_VERSION
#define BRIDGE_VERSION "dev"
#endif
#ifndef RUNTIME_VERSION
#define RUNTIME_VERSION "unknown"
#endif

// Mono's CoreCLR-style host API (mono/mini/monovm.c); not in the public headers.
extern int monovm_initialize(int propertyCount, const char **propertyKeys, const char **propertyValues);
extern int monovm_create_delegate(const char *assemblyName, const char *typeName, const char *methodName, void **delegate);

// AOT image of System.Private.CoreLib, built with --aot=static,full,interp. Without
// a JIT the interpreter takes its native<->managed trampolines from this image.
extern void *mono_aot_module_System_Private_CoreLib_info;

// BCL native helpers linked into this dylib; the table is generated by build.sh.
typedef struct {
    const char *name;
    void *fn;
} bridge_sym;
extern const bridge_sym bridge_native_syms[];
extern const size_t bridge_native_syms_count;

static pthread_mutex_t log_lock = PTHREAD_MUTEX_INITIALIZER;
static FILE *log_file;
static char dotnet_dir[1024];
static int verbose;

static void blog(const char *fmt, ...) __attribute__((format(printf, 1, 2)));
static void blog(const char *fmt, ...) {
    if (!log_file)
        return;
    struct timeval tv;
    gettimeofday(&tv, NULL);
    pthread_mutex_lock(&log_lock);
    fprintf(log_file, "[%ld.%03d] ", (long)tv.tv_sec, (int)(tv.tv_usec / 1000));
    va_list ap;
    va_start(ap, fmt);
    vfprintf(log_file, fmt, ap);
    va_end(ap);
    fputc('\n', log_file);
    fflush(log_file);
    pthread_mutex_unlock(&log_lock);
}

static void mono_log(const char *domain, const char *level, const char *message, mono_bool fatal, void *user_data) {
    blog("mono[%s/%s] %s", domain ? domain : "-", level ? level : "-", message ? message : "");
    if (fatal) {
        blog("fatal Mono error, aborting");
        abort();
    }
}

static int sym_cmp(const void *key, const void *elem) {
    return strcmp((const char *)key, ((const bridge_sym *)elem)->name);
}

static const void *pinvoke_override(const char *libraryName, const char *entrypointName) {
    if (!libraryName || !entrypointName)
        return NULL;
    if (!strcmp(libraryName, "libSystem.Native") ||
        !strcmp(libraryName, "libSystem.IO.Compression.Native") ||
        !strcmp(libraryName, "libSystem.Security.Cryptography.Native.Apple")) {
        const bridge_sym *s = bsearch(entrypointName, bridge_native_syms, bridge_native_syms_count,
                                      sizeof(bridge_sym), sym_cmp);
        if (!s)
            blog("pinvoke: %s!%s is not linked into the bridge", libraryName, entrypointName);
        return s ? s->fn : NULL;
    }
    if (!strcmp(libraryName, "__Internal") || !strcmp(libraryName, "sts2")) {
        // The port's own iOS helpers are compiled into the app executable.
        void *fn = dlsym(RTLD_DEFAULT, entrypointName);
        if (!fn)
            blog("pinvoke: %s!%s not found", libraryName, entrypointName);
        return fn;
    }
    return NULL; // let Mono resolve it the usual way
}

__attribute__((visibility("default")))
int coreclr_initialize(const char *exePath, const char *appDomainFriendlyName,
                       int propertyCount, const char **propertyKeys, const char **propertyValues,
                       void **hostHandle, unsigned int *domainId) {
    blog("coreclr_initialize called by Godot (%d properties)", propertyCount);

    // Every .dll in Documents/dotnet is a trusted platform assembly.
    char *tpa;
    @autoreleasepool {
        NSString *dir = @(dotnet_dir);
        NSArray<NSString *> *names = [[NSFileManager.defaultManager contentsOfDirectoryAtPath:dir error:nil]
            sortedArrayUsingSelector:@selector(compare:)];
        NSMutableArray<NSString *> *paths = [NSMutableArray array];
        for (NSString *name in names) {
            if ([name.pathExtension.lowercaseString isEqualToString:@"dll"])
                [paths addObject:[dir stringByAppendingPathComponent:name]];
        }
        blog("%lu assemblies in %s", (unsigned long)paths.count, dotnet_dir);
        tpa = strdup([paths componentsJoinedByString:@":"].UTF8String);
    }

    char base_dir[1100];
    snprintf(base_dir, sizeof base_dir, "%s/", dotnet_dir);
    char pinvoke[32];
    snprintf(pinvoke, sizeof pinvoke, "%p", (void *)&pinvoke_override);

    // Godot passes no properties of its own, so these are all Mono gets. Kept
    // static and copied because Mono reads them again when the runtime starts.
    static const char *keys[] = {
        "TRUSTED_PLATFORM_ASSEMBLIES",
        "APP_PATHS",
        "NATIVE_DLL_SEARCH_DIRECTORIES",
        "APP_CONTEXT_BASE_DIRECTORY",
        "RUNTIME_IDENTIFIER",
        "PINVOKE_OVERRIDE",
        "System.Globalization.Invariant",
        "System.Globalization.PredefinedCulturesOnly",
    };
    static const char *values[sizeof keys / sizeof keys[0]];
    values[0] = tpa;
    values[1] = strdup(dotnet_dir);
    values[2] = strdup(dotnet_dir);
    values[3] = strdup(base_dir);
    values[4] = "ios-arm64";
    values[5] = strdup(pinvoke);
    // ICU is not bundled, so culture data comes from invariant mode.
    values[6] = "true";
    values[7] = "false";
    setenv("DOTNET_SYSTEM_GLOBALIZATION_INVARIANT", "1", 1);
    setenv("DOTNET_SYSTEM_GLOBALIZATION_PREDEFINED_CULTURES_ONLY", "0", 1);

    mono_trace_set_log_handler(mono_log, NULL);
    mono_trace_set_level_string(verbose ? "debug" : "warning");
    if (verbose)
        mono_trace_set_mask_string("asm,aot,dll,cfg");
    mono_set_signal_chaining(1);
    mono_set_crash_chaining(1);

    // Read the .pdb files next to the assemblies, so exception stack traces
    // carry file names and line numbers.
    mono_debug_init(MONO_DEBUG_FORMAT_MONO);
    // No inlining in the interpreter: every call keeps its own stack frame, and
    // a redirected (patched) method can't be bypassed by an inlined copy.
    setenv("MONO_INTERPRETER_OPTIONS", "-inline", 1);

    mono_aot_register_module((void **)mono_aot_module_System_Private_CoreLib_info);
    mono_jit_set_aot_mode(MONO_AOT_MODE_INTERP);

    int rc = monovm_initialize((int)(sizeof keys / sizeof keys[0]), keys, values);
    blog("monovm_initialize -> 0x%x", rc);
    if (hostHandle)
        *hostHandle = (void *)1;
    if (domainId)
        *domainId = 1;
    return rc;
}

__attribute__((visibility("default")))
int coreclr_create_delegate(void *hostHandle, unsigned int domainId,
                            const char *assemblyName, const char *typeName, const char *methodName,
                            void **delegate) {
    blog("coreclr_create_delegate(%s, %s, %s)", assemblyName, typeName, methodName);
    int rc = monovm_create_delegate(assemblyName, typeName, methodName, delegate);
    blog("monovm_create_delegate -> 0x%x, entry point %p", rc, delegate ? *delegate : NULL);
    if (rc == 0)
        blog("Mono is now running the game's C# code");
    return rc;
}

__attribute__((constructor))
static void bridge_load(void) {
    @autoreleasepool {
        NSFileManager *fm = NSFileManager.defaultManager;
        NSString *docs = NSSearchPathForDirectoriesInDomains(NSDocumentDirectory, NSUserDomainMask, YES).firstObject;
        NSString *caches = NSSearchPathForDirectoriesInDomains(NSCachesDirectory, NSUserDomainMask, YES).firstObject;
        NSString *dotnet = [docs stringByAppendingPathComponent:@"dotnet"];
        strlcpy(dotnet_dir, dotnet.fileSystemRepresentation, sizeof dotnet_dir);
        [fm createDirectoryAtPath:dotnet withIntermediateDirectories:YES attributes:nil error:nil];
        verbose = [fm fileExistsAtPath:[dotnet stringByAppendingPathComponent:@"verbose"]];

        // dyld may map this file a second time when Godot dlopens it through the
        // symlink; only the first mapping sets things up.
        BOOL first = getenv("STS2MONO_LOADED") == NULL;
        setenv("STS2MONO_LOADED", "1", 1);

        NSString *logPath = [dotnet stringByAppendingPathComponent:@"bridge.log"];
        log_file = fopen(logPath.fileSystemRepresentation, first ? "w" : "a");
        Dl_info info = {0};
        dladdr((const void *)&bridge_load, &info);
        blog("StS2Mono %s (Mono %s) loaded from %s%s", BRIDGE_VERSION, RUNTIME_VERSION,
             info.dli_fname ? info.dli_fname : "?", first ? "" : " (second mapping)");
        if (!first || !info.dli_fname)
            return;

        // What the original StS2Mod.dylib did: the game looks for mods next to its executable.
        NSString *mods = [docs stringByAppendingPathComponent:@"mods"];
        NSString *appMods = [NSBundle.mainBundle.bundlePath stringByAppendingPathComponent:@"mods"];
        [fm createDirectoryAtPath:mods withIntermediateDirectories:YES attributes:nil error:nil];
        NSError *err = nil;
        if (![fm destinationOfSymbolicLinkAtPath:appMods error:nil] && ![fm fileExistsAtPath:appMods]) {
            if (![fm createSymbolicLinkAtPath:appMods withDestinationPath:mods error:&err])
                blog("could not link %s: %s", appMods.UTF8String, err.localizedDescription.UTF8String);
        }

        // Point Godot's runtime probe at this dylib, or remove the link so the game uses NativeAOT.
        NSString *dataDir = [caches stringByAppendingPathComponent:@"data_sts2_ios_arm64"];
        NSString *probe = [dataDir stringByAppendingPathComponent:@"libmonosgen-2.0.so"];
        [fm removeItemAtPath:probe error:nil];

        BOOL disabled = [fm fileExistsAtPath:[dotnet stringByAppendingPathComponent:@"DISABLE"]];
        BOOL haveGame = [fm fileExistsAtPath:[dotnet stringByAppendingPathComponent:@"sts2.dll"]];
        BOOL haveCoreLib = [fm fileExistsAtPath:[dotnet stringByAppendingPathComponent:@"System.Private.CoreLib.dll"]];
        if (disabled || !haveGame || !haveCoreLib) {
            blog("Mono not enabled (DISABLE file: %d, sts2.dll: %d, System.Private.CoreLib.dll: %d); "
                 "the game will use its NativeAOT build", disabled, haveGame, haveCoreLib);
            return;
        }

        [fm createDirectoryAtPath:dataDir withIntermediateDirectories:YES attributes:nil error:nil];
        // Godot wipes and re-extracts this folder unless this manifest matches the
        // one packed in sts2.pck, which is empty on this port.
        NSString *manifest = [dataDir stringByAppendingPathComponent:@".dotnet-publish-manifest"];
        if (![fm fileExistsAtPath:manifest])
            [fm createFileAtPath:manifest contents:[NSData data] attributes:nil];
        err = nil;
        if (![fm createSymbolicLinkAtPath:probe withDestinationPath:@(info.dli_fname) error:&err]) {
            blog("could not link %s: %s", probe.UTF8String, err.localizedDescription.UTF8String);
            return;
        }
        blog("linked %s to this dylib", probe.UTF8String);

        // Keep stdout/stderr (Mono's own messages, Console.WriteLine) for debugging.
        NSString *console = [dotnet stringByAppendingPathComponent:@"console.log"];
        int fd = open(console.fileSystemRepresentation, O_WRONLY | O_CREAT | O_TRUNC | O_APPEND, 0644);
        if (fd >= 0) {
            dup2(fd, STDOUT_FILENO);
            dup2(fd, STDERR_FILENO);
            close(fd);
            setvbuf(stdout, NULL, _IOLBF, 0);
        }
    }
}
